/* 读取现有商品名称，用于去重 */
const DATA = { products: [] };
const dataDir = path.join(ROOT, '数据/商品');
for (const f of fs.readdirSync(dataDir)) {
  if (f.endsWith('.js')) {
    try { eval(fs.readFileSync(path.join(dataDir, f), 'utf8')); } catch (e) { console.error('load fail', f, e.message); }
  }
}
const seenKey = new Set(DATA.products.map(p => p.brand + '|' + p.name));

const out = [];
let seq = 0;
const idUsed = new Set(DATA.products.map(p => p.id));
const dup = [];
for (const kind of Object.keys(T)) {
  const tpl = NUT[kind];
  const cat = CAT[kind];
  for (const [brand, name, price] of T[kind]) {
    const key = brand + '|' + name;
    if (seenKey.has(key)) { dup.push('重复:' + key); continue; }
    seenKey.add(key);
    let id;
    do { id = 'x' + String(++seq).padStart(4, '0'); } while (idUsed.has(id));
    idUsed.add(id);
    out.push({
      id, brand, name, cat, price,
      sv: tpl.sv, nut: Object.assign({}, tpl.nut), eff: Object.assign({}, tpl.eff),
      lv: tpl.lv, kind, shelf: tpl.shelf
    });
  }
}

/* 校验 */
const nameSet = new Set();
const idSet = new Set();
const errors = [];
for (const p of out) {
  const key = p.brand + '|' + p.name;
  if (nameSet.has(key)) errors.push('生成内重复:' + key);
  nameSet.add(key);
  if (idSet.has(p.id)) errors.push('id重复:' + p.id);
  idSet.add(p.id);
  if (!(p.price > 0)) errors.push('价格异常:' + p.name);
  if (!NUT[p.kind]) errors.push('kind非法:' + p.kind + ' ' + p.name);
}

const total = DATA.products.length + out.length;
console.log('现有:', DATA.products.length, '新增:', out.length, '总计:', total);
if (dup.length) console.log('与现有重复(已跳过):', dup.join('; '));
if (errors.length) { console.error('校验失败:'); errors.forEach(e => console.error(' -', e)); process.exit(1); }
if (total < 2000) { console.error('不足2000!'); process.exit(1); }
if (total !== new Set([...DATA.products.map(p => p.id), ...out.map(p => p.id)]).size) { console.error('id总数不一致!'); process.exit(1); }

